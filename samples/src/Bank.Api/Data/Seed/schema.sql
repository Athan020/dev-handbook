CREATE TABLE accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    holder_name character varying(200) NOT NULL,
    currency character(3) NOT NULL,
    opened_at timestamp with time zone NOT NULL,
    version integer NOT NULL DEFAULT 1,
    balance numeric(18,2) NOT NULL DEFAULT 0.0,
    balance_version integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_accounts PRIMARY KEY (id)
);


CREATE TABLE idempotency_keys (
    payer_account_id integer NOT NULL,
    key character varying(100) NOT NULL,
    request_hash character varying(64) NOT NULL,
    status_code integer,
    response jsonb,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_idempotency_keys PRIMARY KEY (payer_account_id, key)
);


CREATE TABLE outbox_messages (
    id uuid NOT NULL,
    position bigint GENERATED ALWAYS AS IDENTITY,
    exchange character varying(100) NOT NULL DEFAULT 'transfers',
    routing_key character varying(100) NOT NULL DEFAULT 'transfer.completed',
    type character varying(100) NOT NULL,
    payload jsonb NOT NULL,
    created_at timestamp with time zone NOT NULL,
    published_at timestamp with time zone,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (id)
);


CREATE TABLE outgoing_payments (
    id uuid NOT NULL,
    from_account_id integer NOT NULL,
    amount numeric(18,2) NOT NULL,
    to_bank character varying(50) NOT NULL,
    to_account character varying(50) NOT NULL,
    status character varying(20) NOT NULL,
    attempts integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    resolved_at timestamp with time zone,
    CONSTRAINT pk_outgoing_payments PRIMARY KEY (id)
);


CREATE TABLE processed_messages (
    consumer character varying(100) NOT NULL,
    message_id character varying(100) NOT NULL,
    processed_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_processed_messages PRIMARY KEY (consumer, message_id)
);


CREATE TABLE reward_points (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    account_id integer NOT NULL,
    transfer_id uuid NOT NULL,
    points integer NOT NULL,
    awarded_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_reward_points PRIMARY KEY (id)
);


CREATE TABLE statement_accounts (
    account_id integer NOT NULL,
    last_sequence integer NOT NULL,
    balance numeric(18,2) NOT NULL,
    CONSTRAINT pk_statement_accounts PRIMARY KEY (account_id)
);


CREATE TABLE statement_problems (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    account_id integer NOT NULL,
    sequence integer NOT NULL,
    problem character varying(200) NOT NULL,
    at timestamp with time zone NOT NULL,
    CONSTRAINT pk_statement_problems PRIMARY KEY (id)
);


CREATE TABLE transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    account_id integer NOT NULL,
    counterparty_account_id integer,
    amount numeric(18,2) NOT NULL,
    description character varying(200) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (id),
    CONSTRAINT fk_transactions_accounts_account_id FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_transactions_accounts_counterparty_account_id FOREIGN KEY (counterparty_account_id) REFERENCES accounts (id) ON DELETE RESTRICT
);


CREATE INDEX ix_idempotency_keys_created_at ON idempotency_keys (created_at);


CREATE INDEX ix_outbox_messages_created_at ON outbox_messages (created_at) WHERE published_at IS NULL;


CREATE INDEX ix_outbox_messages_position ON outbox_messages (position) WHERE published_at IS NULL;


CREATE INDEX ix_outgoing_payments_created_at ON outgoing_payments (created_at) WHERE status = 'Pending';


